import test from 'node:test'
import assert from 'node:assert/strict'
import { Rig } from './support.mjs'

test('系统续办在结案后开立新任期且重放不重复开立', () => {
  const manager = new Rig('Manager', 'work-system-continuation')
  manager.review([{ key: 'job', value: 'do' }])
  const relay = manager.review([{ key: 'job', value: null }])
  manager.send(relay)
  const cleanup = manager.review([])
  manager.send(cleanup)
  const completed = manager.review([])
  manager.confirm(completed.effect, 'Requested')
  const restored = manager.restored()
  const retirement = restored.inspect().rounds.at(-1)
  assert.equal(retirement.providerRunId, manager.lastCommand.providerRunId)
  assert.equal(retirement.stopEffectId, completed.effect.id)
  const command = { type: 'ContinueWork', continuationId: 'conflict-1' }
  assert.equal(manager.call(command, 'before-stop').status, 'Conflict')
  manager.confirm(completed.effect, 'Observed')
  const reopened = manager.call(command, 'continuation-1')
  assert.equal(reopened.status, 'Applied')
  assert.equal(reopened.result.kind, 'Reopened')
  assert.deepEqual(manager.work.inspect().barrier, {
    toolCallId: retirement.toolCallId,
    successorTenureId: reopened.result.incumbencyId,
  })
  manager.restored()
  assert.equal(manager.call(command, 'continuation-1').status, 'Replayed')
  assert.equal(manager.call(command, 'continuation-2').status, 'Observed')
  assert.equal(manager.call({ type: 'ContinueWork', continuationId: 'conflict-2' }, 'continuation-3').status, 'Conflict')
  manager.restored()
  const reviewed = manager.review([{ key: 'conflict', value: 'resolve' }])
  assert.equal(reviewed.kind, 'Reviewed')
  assert.equal(reviewed.incumbencyId, reopened.result.incumbencyId)
})

test('SPEC[lifecycle-007] empty asks, relay, advance, launches, cleanup and reopen', () => {
  const origin = new Rig()
  const tenures = []
  for (let index = 0; index < 3; index += 1) {
    const asked = origin.review([])
    assert.equal(asked.kind, 'Asked')
    assert.equal(asked.effect.text, '我需要干什么？')
    tenures.push(asked.incumbencyId)
    origin.park(asked)
  }
  assert.equal(new Set(tenures).size, 1)
  assert.equal(origin.work.history().flatMap(frame => frame.events).filter(event => event.type === 'Reviewed').length, 0)
  assert.equal(origin.work.history().flatMap(frame => frame.events).filter(event => event.type === 'IncumbencyRetired').length, 0)
  origin.restored()
  console.log('three empty asks only')

  const reviewed = origin.review([{ key: 'need', value: 'scope' }])
  assert.equal(reviewed.kind, 'Reviewed')
  const cleared = origin.review([{ key: 'need', value: null }])
  assert.equal(cleared.kind, 'Relayed')
  assert.ok(cleared.barrierId)
  origin.restored()
  console.log('clear-then-Relay')

  origin.send(cleared)
  const advanced = origin.review([])
  assert.equal(advanced.kind, 'Advanced')
  assert.equal(advanced.incumbencyId, cleared.successorId)
  assert.equal(origin.work.history().at(-1).events.some(event => event.type === 'ContextBarrier'), false)
  origin.restored()
  console.log('successor first empty Advance')

  origin.send(advanced)
  origin.review([{ key: 'path', value: 'one' }])
  const secondRelay = origin.review([{ key: 'path', value: null }])
  origin.send(secondRelay)
  const kept = origin.review([{ key: 'check', value: 'open' }])
  assert.equal(kept.kind, 'Reviewed')
  const thirdRelay = origin.review([{ key: 'check', value: null }])
  assert.equal(thirdRelay.kind, 'Relayed')
  origin.restored()
  console.log('successor non-empty then empty Relay')

  const plan = new Rig('Plan', 'work-plan')
  for (const next of ['理解与路径', '流程与伪代码', '待执行']) {
    plan.review([{ key: 'item', value: next }])
    const relay = plan.review([{ key: 'item', value: null }])
    plan.send(relay)
    const step = plan.review([])
    assert.equal(step.kind, 'Advanced')
    assert.equal(step.milestone, next)
    plan.send(step)
  }
  assert.equal(plan.work.inspect().phase, 'Ready')
  const same = { type: 'Review', office: 'Plan', providerRunId: 'run-1', toolCallId: 'once', updates: [] }
  const once = plan.apply(same, 'once')
  assert.equal(plan.call(same, 'once').status, 'Replayed')
  assert.equal(plan.work.inspect().launches.length, 1)
  const ids = ['a', 'b', 'c'].map(toolCallId => plan.review([], { toolCallId }).effect.id)
  assert.equal(new Set([once.effect.id, ...ids]).size, 4)
  assert.equal(plan.work.inspect().milestone, '待执行')
  plan.restored()
  console.log('one replay vs three distinct launches')

  const manager = new Rig('Manager', 'work-manager')
  manager.review([{ key: 'job', value: 'do' }])
  const relay = manager.review([{ key: 'job', value: null }])
  manager.send(relay)
  const cleanup = manager.review([])
  assert.equal(cleanup.milestone, '收尾')
  manager.send(cleanup)
  const blocked = manager.call({
    type: 'Review', office: 'Manager', providerRunId: 'run-1', toolCallId: 'blocked', updates: [], blockers: ['lock'],
  })
  assert.equal(blocked.result.kind, 'Blocked')
  const closed = manager.review([])
  assert.equal(closed.kind, 'Completed')
  assert.equal(closed.effect.kind, 'Stop')
  manager.confirm(closed.effect, 'Requested')
  assert.equal(manager.work.inspect().completed, true)
  const late = manager.call({ type: 'Review', office: 'Manager', providerRunId: 'run-1', toolCallId: 'late', updates: [] })
  assert.equal(late.status, 'Conflict')
  assert.equal(late.reason, 'Work is complete')
  manager.restored()
  console.log('cleanup close')

  const advisor = manager.call({ type: 'OperatorMessage', kind: 'Advisor', messageId: 'steer-1' })
  const agent = manager.call({ type: 'OperatorMessage', kind: 'Agent', messageId: 'agent-1' })
  assert.equal(advisor.result.kind, 'Ignored')
  assert.equal(agent.result.kind, 'Ignored')
  assert.equal(manager.work.inspect().completed, true)
  const reopened = manager.apply({ type: 'OperatorMessage', kind: 'Operator', messageId: 'operator-1' })
  assert.equal(reopened.kind, 'Reopened')
  assert.equal(manager.work.inspect().milestone, '执行')
  assert.equal(manager.work.inspect().active.origin, 'Originator')
  const again = manager.call({ type: 'OperatorMessage', kind: 'Operator', messageId: 'operator-2' })
  assert.equal(again.status, 'Conflict')
  assert.equal(manager.work.history().flatMap(frame => frame.events).filter(event => event.type === 'IncumbencyOpened' && event.messageId === 'operator-1').length, 1)
  assert.equal(manager.work.history().flatMap(frame => frame.events).filter(event => event.messageId === 'steer-1' || event.messageId === 'agent-1').length, 0)
  manager.restored()
  console.log('one operator reopen and zero Advisor/agent reopens')
})
