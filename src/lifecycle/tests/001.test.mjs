import test from 'node:test'
import assert from 'node:assert/strict'
import { Rig } from './support.mjs'

test('SPEC[lifecycle-001] the first empty review opens the tenure and asks in one record', () => {
  const rig = new Rig()
  assert.equal(rig.work.recover().next, 'Review')
  assert.equal(rig.work.recover().wait, 'AwaitReview')
  const asked = rig.review([])
  assert.equal(asked.kind, 'Asked')
  assert.equal(asked.effect.kind, 'Ask')
  assert.deepEqual(rig.work.history()[0].events.map(event => event.type), ['WorkOpened', 'IncumbencyOpened', 'QuestionRequested'])
  assert.equal(rig.work.history()[0].events.some(event => event.type === 'Reviewed'), false)
  assert.equal(rig.work.inspect().active.id, asked.incumbencyId)
  assert.equal(rig.work.inspect().active.origin, 'Originator')
  assert.equal(rig.work.inspect().milestone, '事实与取舍')
  assert.equal(rig.work.recover().next, 'ConfirmEffect')
  rig.restored()
})

test('SPEC[lifecycle-001] a non-empty first review commits the ledger in the opening record', () => {
  const rig = new Rig('Manager', 'work-manager')
  const reviewed = rig.review([{ key: 'gap', value: 'fix' }])
  assert.equal(reviewed.kind, 'Reviewed')
  assert.equal(reviewed.effect, null)
  assert.deepEqual(reviewed.obligations, [{ key: 'gap', value: 'fix' }])
  assert.deepEqual(rig.work.history()[0].events.map(event => event.type), ['WorkOpened', 'IncumbencyOpened', 'Reviewed'])
  assert.equal(rig.work.inspect().office, 'Manager')
  assert.equal(rig.work.inspect().active.substantive, true)
  rig.restored()
})

test('SPEC[lifecycle-001] relay and advance are single records', () => {
  const rig = new Rig()
  rig.review([{ key: 'gap', value: 'fix' }])
  const relay = rig.review([{ key: 'gap', value: null }])
  assert.equal(relay.kind, 'Relayed')
  assert.deepEqual(rig.work.history().at(-1).events.map(event => event.type), ['IncumbencyRetired', 'ContextBarrier', 'IncumbencyOpened', 'PromptObliged'])
  assert.equal(relay.effect.promptKind, 'Successor')
  assert.equal(relay.effect.text, '继任「事实与取舍」。先独立验收。')
  const barrierEvent = rig.work.history().at(-1).events.find(event => event.type === 'ContextBarrier')
  assert.equal(rig.work.inspect().barrier.toolCallId, barrierEvent.toolCallId)
  assert.equal(rig.work.inspect().barrier.successorTenureId, relay.successorId)
  rig.send(relay)
  const advanced = rig.review([])
  assert.equal(advanced.kind, 'Advanced')
  assert.equal(advanced.incumbencyId, relay.successorId)
  assert.deepEqual(rig.work.history().at(-1).events.map(event => event.type), ['MilestoneAdvanced', 'PromptObliged'])
  assert.equal(advanced.effect.text, '进入「理解与路径」。')
  assert.equal(rig.work.inspect().active.origin, 'Originator')
  rig.restored()
})
