module Wanxiangli.Advisor.AdvisorLaw

open System
open System.Collections.Generic
open Fable.Core
open Fable.Core.JsInterop

[<Emit("$0 === null || $0 === undefined")>]
let private isAbsent (_value: obj) : bool = jsNative

[<Emit("Array.isArray($0)")>]
let private isArray (_value: obj) : bool = jsNative

[<Emit("typeof $0 === 'string'")>]
let private isString (_value: obj) : bool = jsNative

[<Emit("Number.isInteger($0) && $0 >= 0")>]
let private isAnchor (_value: obj) : bool = jsNative

[<Emit("$0[$1]")>]
let private field (_value: obj) (_name: string) : obj = jsNative

[<Emit("Object.freeze($0)")>]
let private freeze (_value: obj) : obj = jsNative

let private malformed (what: string) : 'T =
    raise (ArgumentException(sprintf "wanxiangli/advisor: malformed %s" what))

let private array (what: string) (value: obj) : obj array =
    if isArray value then unbox<obj array> value else malformed what

let private anchorOf (what: string) (value: obj) : int =
    if isAnchor value then unbox<int> value else malformed what

let private textOf (what: string) (value: obj) : string =
    if isString value then unbox<string> value else malformed what

let private callerOf (value: obj) : string =
    if isString value then
        unbox<string> value
    else
        malformed "caller session id"

/// LEMMA 1: a material identity is its representative anchor plus the exact rendered
/// text, length-prefixed so no (anchor, text) pair can collide with another.
let private keyOf (anchor: int) (text: string) : string =
    string anchor + ":" + string text.Length + ":" + text

let private materialKeyImpl (anchor: obj) (text: obj) : string =
    keyOf (anchorOf "anchor" anchor) (textOf "text" text)

/// LEMMA 2: the complete view is generated by the caller first; delivery facts filter
/// its output, never its input. Order is the view's order; nothing is merged or sorted.
let private planImpl (delivered: obj) (material: obj) : obj =
    let seen = HashSet<string>()

    array "delivered" delivered
    |> Array.iter (fun key -> seen.Add(textOf "delivered key" key) |> ignore)

    let pieces =
        array "material" material
        |> Array.map (fun item ->
            if isAbsent item then malformed "material entry"
            let anchor = anchorOf "material anchor" (field item "anchor")
            let text = textOf "material text" (field item "text")
            anchor, text, keyOf anchor text)

    let delta =
        pieces |> Array.filter (fun (_, _, key) -> not (seen.Contains key))

    freeze (
        createObj
            [ "delta" ==> (delta |> Array.map (fun (a, t, _) -> freeze (createObj [ "anchor" ==> a; "text" ==> t ])))
              "deliveredAnchors" ==> (pieces |> Array.map (fun (a, _, _) -> a) |> Array.distinct)
              "deliveredMaterial" ==> (delta |> Array.map (fun (_, _, k) -> k))
              "hasNewMaterial" ==> (delta.Length > 0) ]
    )

/// LEMMA 4: the answer is the last assistant message whose text is not blank. Role is
/// matched case-insensitively; anything else (user, tool, blank) is never advice.
let private answerImpl (messages: obj) : obj =
    let picked =
        array "messages" messages
        |> Array.rev
        |> Array.tryPick (fun message ->
            if isAbsent message then
                None
            else
                let role = field message "role"
                let text = field message "text"

                if isString role
                   && String.Equals(unbox<string> role, "assistant", StringComparison.OrdinalIgnoreCase)
                   && isString text
                   && not (String.IsNullOrWhiteSpace(unbox<string> text)) then
                    Some(unbox<string> text)
                else
                    None)

    match picked with
    | Some text -> box text
    | None -> null

/// LEMMA 3: process-live delivered-material ledger, isolated per caller session and per
/// instance. Only `record` advances it, and it never forgets a key except by `clear`.
[<AttachMembers>]
type AdvisorLedger() =
    let cursors = Dictionary<string, HashSet<string>>()

    member _.delivered(caller: obj) : string array =
        match cursors.TryGetValue(callerOf caller) with
        | true, keys -> keys |> Seq.sort |> Seq.toArray
        | false, _ -> [||]

    member _.record(caller: obj, keys: obj) : unit =
        let id = callerOf caller
        let incoming = array "keys" keys |> Array.map (textOf "key")

        if incoming.Length > 0 then
            let cursor =
                match cursors.TryGetValue id with
                | true, existing -> existing
                | false, _ ->
                    let fresh = HashSet<string>()
                    cursors[id] <- fresh
                    fresh

            incoming |> Array.iter (fun key -> cursor.Add key |> ignore)

    member _.clear(caller: obj) : unit = cursors.Remove(callerOf caller) |> ignore
    member _.clearAll() : unit = cursors.Clear()

/// Pure advisor consult laws: material identity, delta planning and prose read-back.
[<AttachMembers>]
type AdvisorLaw() =
    member _.contractVersion = 1
    member _.materialKey(anchor: obj, text: obj) : string = materialKeyImpl anchor text
    member _.plan(delivered: obj, material: obj) : obj = planImpl delivered material
    member _.answer(messages: obj) : obj = answerImpl messages
    /// A fresh, empty delivered-material ledger (LEMMA 3).
    member _.ledger() : AdvisorLedger = AdvisorLedger()
