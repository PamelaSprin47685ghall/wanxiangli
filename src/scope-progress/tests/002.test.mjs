import test from 'node:test'
import assert from 'node:assert/strict'
import { AdvisorProcessQueue } from '../../../dist/scope-progress/AdvisorFlow.js'

test('SPEC[scope-progress-002] per-session single active and one coalesced waiting Process',()=>{
  const q=AdvisorProcessQueue()
  const first=q.enqueue('s','e','p1')
  assert.equal(first.start,true)
  const second=q.enqueue('s','e','p2')
  assert.equal(second.start,false)
  const third=q.enqueueWithNote('s','e','p3','report p3: remaining increased')
  assert.equal(third.start,false)
  assert.equal(third.processId,second.processId)
  assert.deepEqual(Array.from(third.triggers),['p2','p3'])
  assert.deepEqual(Array.from(third.notes),['','report p3: remaining increased'])
  assert.equal(q.enqueue('s','e','p1').accepted,false)
  assert.equal(q.enqueue('s','e','p3').accepted,false)
  assert.equal(q.advance('s',first.processId,2).ok,false,'must finish stages in order')
  for(let phase=1;phase<=4;phase++)assert.equal(q.advance('s',first.processId,phase).ok,true)
  const next=q.finish('s',first.processId)
  assert.equal(next.start,true)
  assert.equal(next.processId,second.processId)
  assert.deepEqual(Array.from(next.triggers),['p2','p3'])
  for(let phase=1;phase<=4;phase++)assert.equal(q.advance('s',second.processId,phase).ok,true)
  assert.equal(q.finish('s',second.processId).start,false)
})

test('SPEC[scope-progress-002] per-session isolation, epoch reset and late phases',()=>{
  const q=AdvisorProcessQueue()
  const a=q.enqueue('a','one','report-one')
  const b=q.enqueue('b','one','report-other')
  assert.notEqual(a.processId,b.processId)
  q.enqueue('a','one','later')
  q.reset('a','two')
  assert.equal(q.advance('a',a.processId,1).ok,false)
  const current=q.enqueue('a','two','fresh')
  assert.equal(current.start,true)
  assert.notEqual(current.processId,a.processId)
  assert.equal(q.advance('b',b.processId,1).ok,true)
  const other=q.enqueue('b','one','waiting')
  assert.equal(q.fail('b',b.processId).processId,other.processId,'failure must release queue for its one coalesced waiting process')
  q.clear('b')
  assert.equal(q.advance('b',b.processId,2).ok,false)
})

test('SPEC[scope-progress-002] a settled trigger cannot create a second Advisor process', () => {
  const q = AdvisorProcessQueue()
  const first = q.enqueue('s', 'e1', 'report-one')
  for (let phase = 1; phase <= 4; phase++) assert.equal(q.advance('s', first.processId, phase).ok, true)
  assert.equal(q.finish('s', first.processId).start, false)
  const replay = q.enqueue('s', 'e1', 'report-one')
  assert.equal(replay.start, false, 'a finished consultation remains identified for this scope')
  assert.equal(replay.accepted, false)
  const next = q.enqueue('s', 'e1', 'report-two')
  assert.equal(next.start, true, 'a distinct report can still request advice')
  q.reset('s', 'e2')
  assert.equal(q.enqueue('s', 'e2', 'report-one').start, true, 'a new scope may reuse a report identity')
})

test('SPEC[scope-progress-002] process identity remains stable across restart and unique across sessions and scopes', () => {
  const alpha = AdvisorProcessQueue().enqueue('session-alpha', 'scope-1', 'same-report')
  const restarted = AdvisorProcessQueue().enqueue('session-alpha', 'scope-1', 'same-report')
  const otherSession = AdvisorProcessQueue().enqueue('session-beta', 'scope-1', 'same-report')
  const otherScope = AdvisorProcessQueue().enqueue('session-alpha', 'scope-2', 'same-report')
  const otherReport = AdvisorProcessQueue().enqueue('session-alpha', 'scope-1', 'other-report')
  assert.equal(alpha.processId, restarted.processId, 'the same durable trigger needs a reproducible receipt')
  for (const independent of [otherSession, otherScope, otherReport]) {
    assert.notEqual(alpha.processId, independent.processId, 'unrelated first consultations cannot share a physical receipt')
  }
})
