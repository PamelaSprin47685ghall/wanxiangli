import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { cleanEnvironment } from './build-fixture.mjs'
import { fixture, run, good, change, values, artifacts, alive, waitFor } from './resident-fixture.mjs'

async function compareFresh(directory) {
  const expected = artifacts(directory)
  good(await run(directory, ['--stop']))
  good(await run(directory, ['--force']))
  assert.deepEqual(artifacts(directory), expected)
}

test('WHAT[build-014] same-time edits, real branch switches and damaged outputs retain module-level invalidation', { timeout: 60000 }, async t => {
  const directory = fixture(t)
  const git = (...args) => {
    const result = spawnSync('git', args, { cwd: directory, env: cleanEnvironment(), encoding: 'utf8' })
    assert.equal(result.status, 0, result.stderr)
  }
  git('init', '-q', '--initial-branch=branch-a')
  git('add', 'src')
  git('-c', 'user.name=Build Test', '-c', 'user.email=build@example.invalid', 'commit', '-qm', 'Fixture A')
  const first = good(await run(directory))
  const source = path.join(directory, 'src/alpha/Data.fs')
  const time = fs.statSync(source)
  const beta = path.join(directory, 'dist/beta/Probe.js')
  const betaTime = fs.statSync(beta).mtimeMs
  change(directory, 'alpha', 2)
  fs.utimesSync(source, time.atime, time.mtime)
  const next = good(await run(directory))
  assert.equal(next.workerPid, first.workerPid)
  assert.deepEqual(next.built, ['alpha'])
  assert.equal(fs.statSync(beta).mtimeMs, betaTime)
  assert.deepEqual(values(directory), [2, 3])
  git('switch', '-qc', 'branch-b')
  git('add', 'src')
  git('-c', 'user.name=Build Test', '-c', 'user.email=build@example.invalid', 'commit', '-qm', 'Fixture B')
  git('switch', '-q', 'branch-a')
  assert.deepEqual(good(await run(directory)).built, ['alpha'])
  assert.deepEqual(values(directory), [1, 3])
  git('switch', '-q', 'branch-b')
  assert.deepEqual(good(await run(directory)).built, ['alpha'])
  assert.deepEqual(values(directory), [2, 3])
  const expected = artifacts(directory)
  fs.appendFileSync(beta, '\n// damaged output\n')
  assert.deepEqual(good(await run(directory)).built, ['beta'])
  assert.deepEqual(artifacts(directory), expected)
  fs.rmSync(beta)
  assert.deepEqual(good(await run(directory)).built, ['beta'])
  await compareFresh(directory)
  fs.renameSync(path.join(directory, 'src/alpha'), path.join(directory, 'excluded-alpha'))
  assert.deepEqual(good(await run(directory)).removed, ['alpha'])
  assert.equal(fs.existsSync(path.join(directory, 'dist/alpha')), false)
  fs.renameSync(path.join(directory, 'excluded-alpha'), path.join(directory, 'src/alpha'))
  assert.deepEqual(good(await run(directory)).built, ['alpha'])
  assert.deepEqual(values(directory), [2, 3])
})

test('WHAT[build-014] same-version library and DLL bytes replace the worker and incompatible metadata fails', { timeout: 60000 }, async t => {
  const directory = fixture(t, { privateDependencies: true })
  for (const name of ['alpha', 'beta']) {
    fs.appendFileSync(path.join(directory, 'src', name, 'Probe.fs'),
      '    member _.matches = System.Text.RegularExpressions.Regex.IsMatch("abc", "^a")\n')
  }
  const list = path.join(directory, 'node_modules/@fable-org/fable-library-js/List.js')
  assert.ok(fs.realpathSync(list).startsWith(directory + path.sep))
  const original = fs.readFileSync(list, 'utf8')
  const anchor = 'return FSharpList__get_Length(xs) | 0;'
  assert.ok(original.includes(anchor))
  const first = good(await run(directory))
  fs.writeFileSync(list, original.replace(anchor, 'return (FSharpList__get_Length(xs) | 0) + 10;'))
  const updated = good(await run(directory))
  assert.equal(updated.servicePid, first.servicePid)
  assert.notEqual(updated.workerPid, first.workerPid)
  assert.deepEqual(updated.built, ['alpha', 'beta'])
  assert.deepEqual(values(directory), [1, 13])
  fs.writeFileSync(list, original)
  const restored = good(await run(directory))
  assert.deepEqual(values(directory), [1, 3])
  const assembly = path.join(directory, 'node_modules/@fable-org/fable-metadata/lib/System.Text.RegularExpressions.dll')
  assert.ok(fs.realpathSync(assembly).startsWith(directory + path.sep))
  const bytes = fs.readFileSync(assembly)
  fs.writeFileSync(assembly, Buffer.concat([bytes, Buffer.from([0])]))
  const padded = good(await run(directory))
  assert.notEqual(padded.workerPid, restored.workerPid)
  const time = fs.statSync(assembly)
  fs.writeFileSync(assembly, Buffer.concat([bytes, Buffer.from([1])]))
  fs.utimesSync(assembly, time.atime, time.mtime)
  const changed = good(await run(directory))
  assert.notEqual(changed.workerPid, padded.workerPid)
  const before = artifacts(directory)
  fs.copyFileSync(path.join(path.dirname(assembly), 'System.Collections.dll'), assembly)
  const invalid = await run(directory)
  assert.equal(invalid.ok, false)
  assert.notEqual(invalid.status, 0)
  assert.deepEqual(artifacts(directory), before)
  assert.equal(good(await run(directory, ['--status'])).workerPid, null)
  fs.writeFileSync(assembly, bytes)
  good(await run(directory))
  await compareFresh(directory)
})

test('WHAT[build-014] worker code updates execute new code and coordinator updates restart the service', { timeout: 60000 }, async t => {
  const directory = fixture(t)
  const first = good(await run(directory))
  const worker = path.join(directory, 'scripts/build-worker.mjs')
  const original = fs.readFileSync(worker, 'utf8')
  const anchor = 'stdin: { contents:'
  assert.ok(original.includes(anchor))
  fs.writeFileSync(worker, original.replace(anchor, 'banner: { js: "/* worker revision B */" },\n          ' + anchor))
  const changed = good(await run(directory))
  assert.notEqual(changed.servicePid, first.servicePid)
  await waitFor(() => !alive(first.servicePid) && !alive(first.workerPid))
  assert.deepEqual(changed.built, ['alpha', 'beta'])
  assert.match(fs.readFileSync(path.join(directory, 'dist/alpha/Probe.js'), 'utf8'), /worker revision B/)
  await compareFresh(directory)
  const current = good(await run(directory, ['--status']))
  fs.appendFileSync(path.join(directory, 'scripts/build-service.mjs'), '\n// Coordinator revision B\n')
  const restarted = good(await run(directory))
  assert.notEqual(restarted.servicePid, current.servicePid)
  await waitFor(() => !alive(current.servicePid) && !alive(current.workerPid))
  assert.deepEqual(restarted.built, ['alpha', 'beta'])
  assert.deepEqual(values(directory), [1, 3])
})

test('WHAT[build-014] compile and publication errors preserve old outputs and a retry repairs only dirty modules', { timeout: 60000 }, async t => {
  const directory = fixture(t)
  const first = good(await run(directory))
  const before = artifacts(directory)
  change(directory, 'alpha', '"invalid string"')
  const consumer = path.join(directory, 'src/alpha/Probe.fs')
  const original = fs.readFileSync(consumer, 'utf8')
  fs.writeFileSync(consumer, original.replace('member _.value =', 'member _.value: int ='))
  const invalid = await run(directory)
  assert.equal(invalid.ok, false)
  assert.notEqual(invalid.status, 0)
  assert.deepEqual(artifacts(directory), before)
  await waitFor(() => !alive(first.workerPid))
  change(directory, 'alpha', 2)
  const fixed = good(await run(directory))
  assert.deepEqual(fixed.built, ['alpha'])
  assert.deepEqual(fixed.cached, ['beta'])
  assert.deepEqual(values(directory), [2, 3])
  const expected = artifacts(directory)
  const blocked = path.join(directory, '.build-stamps/alpha.json.new')
  fs.mkdirSync(blocked)
  change(directory, 'alpha', 3)
  const failed = await run(directory)
  assert.equal(failed.ok, false)
  assert.deepEqual(artifacts(directory), expected)
  fs.rmSync(blocked, { recursive: true })
  assert.deepEqual(good(await run(directory)).built, ['alpha'])
  assert.deepEqual(values(directory), [3, 3])
  await compareFresh(directory)
})

test('WHAT[build-014] a service startup error fails promptly and a repaired entry can start', { timeout: 60000 }, async t => {
  const directory = fixture(t)
  const service = path.join(directory, 'scripts/build-service.mjs')
  const original = fs.readFileSync(service, 'utf8')
  fs.appendFileSync(service, '\nthis is invalid JavaScript\n')
  const broken = await run(directory)
  assert.equal(broken.ok, false)
  assert.notEqual(broken.status, 0)
  assert.match(broken.error, /failed to start/)
  assert.ok(broken.wallMs < 10000)
  fs.writeFileSync(service, original)
  good(await run(directory))
  assert.deepEqual(values(directory), [1, 3])
})
