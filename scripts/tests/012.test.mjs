import test from 'node:test'
import assert from 'node:assert/strict'
import { fixture, run, good, change, values, artifacts, alive, waitFor } from './resident-fixture.mjs'

test('WHAT[build-012] independent npm commands reuse one checker and a stopped service restarts lazily', { timeout: 60000 }, async t => {
  const directory = fixture(t)
  assert.equal(good(await run(directory, ['--status'])).running, false)
  const first = good(await run(directory, [], { npm: true }))
  assert.deepEqual(first.built, ['alpha', 'beta'])
  assert.equal(first.checkers, 1)
  assert.ok(!alive(first.clientPid))
  change(directory, 'alpha', 2)
  const next = good(await run(directory, [], { npm: true }))
  assert.notEqual(next.clientPid, first.clientPid)
  assert.equal(next.servicePid, first.servicePid)
  assert.equal(next.compiledBy, first.compiledBy)
  assert.equal(next.checkers, 1)
  assert.deepEqual(next.built, ['alpha'])
  assert.deepEqual(next.cached, ['beta'])
  assert.deepEqual(values(directory), [2, 3])
  const expected = artifacts(directory)
  good(await run(directory, ['--stop']))
  await waitFor(() => !alive(first.servicePid) && !alive(first.workerPid))
  const cached = good(await run(directory, [], { npm: true }))
  assert.notEqual(cached.servicePid, first.servicePid)
  assert.deepEqual(cached.built, [])
  assert.equal(cached.workerPid, null)
  const status = good(await run(directory, ['--status']))
  assert.equal(status.compiler, null)
  const fresh = good(await run(directory, ['--force'], { npm: true }))
  assert.notEqual(fresh.workerPid, first.workerPid)
  assert.deepEqual(artifacts(directory), expected)
})

test('WHAT[build-012] different workspaces do not share a compiler or outputs', { timeout: 60000 }, async t => {
  const first = fixture(t)
  const second = fixture(t)
  change(second, 'alpha', 9)
  const a = good(await run(first))
  const b = good(await run(second))
  assert.notEqual(a.servicePid, b.servicePid)
  assert.notEqual(a.workerPid, b.workerPid)
  assert.deepEqual(values(first), [1, 3])
  assert.deepEqual(values(second), [9, 3])
})


test('WHAT[build-012] status reports an outdated service without restarting it', { timeout: 60000 }, async t => {
  const directory = fixture(t)
  const first = good(await run(directory))
  const before = artifacts(directory)
  const { appendFileSync } = await import('node:fs')
  appendFileSync(directory + '/scripts/build-service.mjs', '\n// Changed service revision\n')
  const status = good(await run(directory, ['--status']))
  assert.equal(status.servicePid, first.servicePid)
  assert.equal(status.workerPid, first.workerPid)
  assert.equal(status.compatible, false)
  assert.deepEqual(artifacts(directory), before)
  const built = good(await run(directory))
  assert.notEqual(built.servicePid, first.servicePid)
  assert.deepEqual(built.built, ['alpha', 'beta'])
  assert.deepEqual(artifacts(directory), before)
})
